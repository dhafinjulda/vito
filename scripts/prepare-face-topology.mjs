import { readFileSync, writeFileSync } from 'node:fs';

// MediaPipe canonical mesh (Apache-2.0); no personal face data is used.
const lines = readFileSync(new URL('./assets/canonical_face_model.obj', import.meta.url), 'utf8').split(/\r?\n/);
const points = lines.filter(line => line.startsWith('v ')).map(line => line.split(/\s+/).slice(1).map(Number));
const triangles = lines.filter(line => line.startsWith('f ')).flatMap(line => line.split(/\s+/).slice(1).map(value => Number(value.split('/')[0]) - 1));
if (points.length !== 468 || triangles.length % 3) throw new Error('Unexpected MediaPipe mesh topology');
const header = '// Generated by scripts/prepare-face-topology.mjs.\n// Canonical face model: Copyright MediaPipe Authors, Apache-2.0.\n// Source and license: see THIRD_PARTY_NOTICES.md.\n';
const eyeSpan = Math.hypot(...points[33].map((value, axis) => value - points[263][axis]));
// Independent upper-face spans; avoid mouth/chin movement and iris/blink points.
const fitPairs = [[33, 263], [133, 362], [70, 300], [54, 284], [21, 251], [10, 168], [151, 6]];
const fitSpans = fitPairs.map(([a, b]) => [a, b, Math.hypot(...points[a].map((value, axis) => value - points[b][axis]))]);
const supportSpans = [[234, 454], [10, 152], [127, 356]].map(([a, b]) => [a, b, Math.hypot(...points[a].map((value, axis) => value - points[b][axis]))]);
writeFileSync(new URL('../packages/sdk/src/glasses/face-topology.ts', import.meta.url), `${header}export const FACE_TRIANGLES = new Uint16Array(${JSON.stringify(triangles)});\nexport const CANONICAL_BRIDGE = ${JSON.stringify(points[168])} as const;\nexport const CANONICAL_EYE_SPAN_CM = ${eyeSpan};\nexport const CANONICAL_FIT_SPANS = ${JSON.stringify(fitSpans)} as const;\nexport const CANONICAL_FACE_SUPPORT_SPANS = ${JSON.stringify(supportSpans)} as const;\n`);
writeFileSync(new URL('../packages/sdk/test/canonical-face.ts', import.meta.url), `${header}export const CANONICAL_FACE = ${JSON.stringify(points)};\n`);
console.log(`Prepared ${points.length} vertices and ${triangles.length / 3} face triangles.`);
