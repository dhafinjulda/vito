import { copyFile, mkdir, readdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const workerDirectory = resolve(root, 'packages/sdk/dist/assets');
const workers = (await readdir(workerDirectory)).filter(name => /^face-worker-[\w-]+\.js$/.test(name));
if (workers.length !== 1) throw new Error(`Expected exactly one built SDK worker, found ${workers.length}. Build vito-sdk first.`);
const source = resolve(workerDirectory, workers[0]);
const destination = resolve(root, 'examples/vanilla/public/vto-face-worker.js');
await mkdir(dirname(destination), { recursive: true });
await copyFile(source, destination);
// The diagnostic must load the same content-addressed runtime as the SDK.
// Keep the legacy public copy for existing offline shells, not new requests.
await writeFile(resolve(root,'examples/vanilla/src/generated-worker-url.ts'),
  `// Generated by scripts/copy-worker.mjs; build the SDK first.\nexport { default } from '../../../packages/sdk/dist/assets/${workers[0]}?url';\n`);
console.log('Prepared the self-contained classic MediaPipe worker for the Vanilla example.');
